primerNumero = int(input("Ingrese el primer numero: "))
segundoNumero = int(input("Ingrese el segundo numero: "))

print(f"Suma: {primerNumero + segundoNumero}")
print(f"Resta: {primerNumero - segundoNumero}")
print(f"Multiplicacion: {primerNumero * segundoNumero}")
print(f"Division: {primerNumero / segundoNumero}")
print(f"Potencia: {primerNumero ** segundoNumero}")
print(f"Resto de la division: {primerNumero % segundoNumero}")